#!/usr/bin/env node
// Builds apps/site/{privacy,terms}/index.html from apps/mobile/assets/legal/*.md, so the app and the
// website always show the same text. `--check` fails (exit 1) if the HTML is out of date; CI runs it.
//
// Handles only the Markdown the legal documents use: # / ## / ### headings, paragraphs, "- " lists,
// pipe tables, **bold**, `code` and [text](https://…) links. Plain email addresses become mailto links.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const DOCS = [
  { md: 'privacy', page: 'privacy', title: 'Privacy policy', description: 'How Qline collects, uses, stores and shares personal information, including Google user data, and your rights under the Philippine Data Privacy Act.' },
  { md: 'terms', page: 'terms', title: 'Terms of service', description: 'The terms for using the Qline app, API and website.' },
];

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function inline(src) {
  const out = [];
  const re = /`([^`]+)`|\*\*(.+?)\*\*|\[([^\]]+)\]\((https:\/\/[^)\s]+)\)|([A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,})/g;
  let last = 0;
  for (const m of src.matchAll(re)) {
    out.push(esc(src.slice(last, m.index)));
    if (m[1] !== undefined) out.push(`<code>${esc(m[1])}</code>`);
    else if (m[2] !== undefined) out.push(`<strong>${inline(m[2])}</strong>`);
    else if (m[3] !== undefined) out.push(`<a href="${esc(m[4])}">${esc(m[3])}</a>`);
    else out.push(`<a href="mailto:${esc(m[5])}">${esc(m[5])}</a>`);
    last = m.index + m[0].length;
  }
  out.push(esc(src.slice(last)));
  return out.join('');
}

const cells = (line) => line.trim().replace(/^\|/, '').replace(/\|$/, '').split('|').map((c) => c.trim());

export function render(md) {
  const lines = md.replace(/\r/g, '').split('\n');
  let title = '', version = '';
  const body = [];
  for (let i = 0; i < lines.length; ) {
    const line = lines[i];
    if (!line.trim()) { i++; continue; }
    let m;
    if ((m = line.match(/^# (.+)$/))) { title = m[1]; i++; continue; }
    if ((m = line.match(/^(#{2,3}) (.+)$/))) { const h = m[1].length; body.push(`<h${h}>${inline(m[2])}</h${h}>`); i++; continue; }
    if (line.startsWith('- ')) {
      const items = [];
      while (i < lines.length && lines[i].startsWith('- ')) items.push(`<li>${inline(lines[i++].slice(2))}</li>`);
      body.push(`<ul>${items.join('')}</ul>`);
      continue;
    }
    if (line.startsWith('|') && /^\|?\s*-{3}/.test(lines[i + 1] ?? '')) {
      const head = cells(line);
      i += 2;
      const rows = [];
      while (i < lines.length && lines[i].startsWith('|')) rows.push(cells(lines[i++]));
      body.push(`<div class="scroll"><table class="scopes"><thead><tr>${head.map((c) => `<th>${inline(c)}</th>`).join('')}</tr></thead><tbody>\n${rows.map((r) => `<tr>${r.map((c) => `<td>${inline(c)}</td>`).join('')}</tr>`).join('\n')}\n</tbody></table></div>`);
      continue;
    }
    const para = [];
    while (i < lines.length && lines[i].trim() && !/^(#|- |\|)/.test(lines[i])) para.push(lines[i++]);
    const text = para.join(' ');
    if (!version && /^Version \d{4}-\d{2}-\d{2}/.test(text)) { version = text; continue; }
    body.push(`<p>${inline(text)}</p>`);
  }
  if (!title || !version) throw new Error('Legal document needs a "# Title" and a "Version YYYY-MM-DD" line');
  return { title, version, body: body.join('\n') };
}

function page(doc, r) {
  const nav = ['privacy', 'terms'].map((p) => `<a href="../${p}/"${p === doc.page ? ' aria-current="page"' : ''}>${p === 'privacy' ? 'Privacy' : 'Terms'}</a>`).join('');
  return `<!doctype html>
<!-- Generated by scripts/build-legal.mjs from apps/mobile/assets/legal/${doc.md}.md. Edit the Markdown, then run: node scripts/build-legal.mjs -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(doc.title)} — Qline</title><meta name="description" content="${esc(doc.description)}"><meta name="theme-color" content="#07100F">
<link rel="icon" href="../icon.svg" type="image/svg+xml"><link rel="stylesheet" href="../styles.css"></head>
<body><header class="top"><div class="wrap"><a class="brand" href="../" aria-label="Qline home"><svg viewBox="0 0 32 32" aria-hidden="true"><path d="M21.88 23.74A11.52 11.52 0 1 1 25.97 17.20M18.75 18.75 29.44 29.44" fill="none" stroke="currentColor" stroke-width="3.2" stroke-linecap="round"/></svg>Qline</a><nav class="links" aria-label="Main"><a href="../">Home</a>${nav}</nav></div></header>
<main><div class="wrap"><article class="doc">
<span class="mono">Legal</span><h1>${inline(r.title)}</h1><p class="meta">${inline(r.version)}</p>
${r.body}
</article></div></main>
<footer><div class="wrap"><span>© 2026 Qline · Davao City, Philippines</span><span><a href="../privacy/">Privacy policy</a> · <a href="../terms/">Terms of service</a> · <a href="mailto:chrono07g@gmail.com">chrono07g@gmail.com</a></span></div></footer>
</body></html>
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const doc of DOCS) {
    const html = page(doc, render(readFileSync(join(root, 'apps/mobile/assets/legal', `${doc.md}.md`), 'utf8')));
    const target = join(root, 'apps/site', doc.page, 'index.html');
    let current = '';
    try { current = readFileSync(target, 'utf8'); } catch {}
    if (current === html) continue;
    if (check) { console.error(`${target} is out of date. Run: node scripts/build-legal.mjs`); stale++; }
    else { writeFileSync(target, html); console.log(`wrote ${target}`); }
  }
  if (stale) process.exit(1);
}
